import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const webDir = fileURLToPath(new URL('..', import.meta.url));
const rootDir = join(webDir, '..', '..');
const target = join(webDir, 'src/shared/domain/http-client/api-schema/api-schema.d.ts');
const header = '/* Generated by `pnpm --filter web api:generate` from the API OpenAPI document. Do not edit. */\n';

// Build the API (and its workspace dependencies), then let it write its document without listening on a port.
execFileSync('pnpm', ['exec', 'turbo', 'run', 'build', '--filter=@house-radar/api'], {
  cwd: rootDir,
  stdio: 'inherit',
  shell: process.platform === 'win32',
});

const scratch = mkdtempSync(join(tmpdir(), 'house-radar-openapi-'));
try {
  const document = join(scratch, 'openapi.json');
  execFileSync(
    process.execPath,
    [
      '--import',
      new URL('./register-extensionless.mjs', import.meta.url).href,
      join(rootDir, 'apps/api/dist/emit-openapi.js'),
      document,
    ],
    { cwd: join(rootDir, 'apps/api'), stdio: 'inherit' },
  );
  const ast = await openapiTS(pathToFileURL(document));
  writeFileSync(target, `${header}${astToString(ast)}`);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
